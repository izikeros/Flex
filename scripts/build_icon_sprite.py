"""Build static/icons/sprite.svg (and the templates/partial/icons.html macro)
from Font Awesome Free SVG glyph data.

Usage (from the theme root):  python3 scripts/build_icon_sprite.py

Font Awesome Free icons are licensed CC BY 4.0 (https://fontawesome.com/license/free);
the attribution is kept in the generated sprite.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "static" / "font-awesome" / "webfonts"
OUT = ROOT / "static" / "icons" / "sprite.svg"
MACRO = ROOT / "templates" / "partial" / "icons.html"

ICONS = {
    "fa-solid-900.svg": [
        "angle-left", "angle-right", "balance-scale", "check", "check-circle",
        "copy", "envelope", "exclamation-circle", "exclamation-triangle",
        "graduation-cap", "info-circle", "lightbulb", "moon", "newspaper",
        "rss", "sun",
    ],
    "fa-brands-400.svg": [
        "facebook", "github", "gitlab", "hacker-news", "instagram", "kaggle",
        "linkedin", "mastodon", "medium", "orcid", "reddit", "stack-overflow",
        "twitter", "youtube",
    ],
}

GLYPH = re.compile(r"<glyph\b[^>]*>", re.S)
ATTR = re.compile(r'([\w-]+)="([^"]*)"')


def glyphs(font):
    text = font.read_text()
    default_adv = re.search(r'<font\b[^>]*horiz-adv-x="(\d+)"', text).group(1)
    for tag in GLYPH.findall(text):
        attrs = dict(ATTR.findall(tag))
        if "glyph-name" in attrs and "d" in attrs:
            yield attrs["glyph-name"], attrs.get("horiz-adv-x", default_adv), attrs["d"]


def main():
    symbols, widths = [], {}
    for font, names in ICONS.items():
        found = {name: (adv, d) for name, adv, d in glyphs(FONTS / font)}
        for name in names:
            adv, d = found[name]
            widths[name] = round(int(adv) / 512, 3)
            # SVG-font glyphs are y-up (ascent 448, descent -64): flip into view
            symbols.append(
                f'<symbol id="icon-{name}" viewBox="0 -448 {adv} 512">'
                f'<path transform="scale(1,-1)" d="{" ".join(d.split())}"/></symbol>'
            )
    OUT.write_text(
        '<svg xmlns="http://www.w3.org/2000/svg">\n'
        "<!-- Font Awesome Free 5.13.0 by @fontawesome - https://fontawesome.com"
        " License - https://fontawesome.com/license/free (Icons: CC BY 4.0) -->\n"
        + "\n".join(symbols)
        + "\n</svg>\n"
    )
    MACRO.write_text(
        "{# Generated by scripts/build_icon_sprite.py - do not edit by hand.\n"
        "   Usage: {% from 'partial/icons.html' import icon with context %}\n"
        "          {{ icon('github') }}  or  {{ icon('rss', 'RSS feed') }} #}\n"
        "{% set icon_widths = " + repr(widths) + " %}\n"
        "{% macro icon(name, label=None) -%}\n"
        '<svg class="icon icon-{{ name }}" style="width: {{ icon_widths.get(name, 1) }}em"'
        ' {% if label %}role="img" aria-label="{{ label }}"{% else %}aria-hidden="true"{% endif %}'
        ' focusable="false"><use href="{{ SITEURL }}/{{ THEME_STATIC_DIR }}/icons/sprite.svg#icon-{{ name }}"></use></svg>\n'
        "{%- endmacro %}\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({len(symbols)} icons) and {MACRO.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
